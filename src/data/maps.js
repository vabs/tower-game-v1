const TYPES = ['single', 'branching', 'open', 'split', 'hybrid'];

/** Template id for a level: `${mapType}_${((level - 1) % 3) + 1}`. Falls back to single_1 with a warning. */
export function mapIdForLevel(levelId) {
  const level = levels[levelId - 1];
  const id = level && TYPES.includes(level.mapType) ? `${level.mapType}_${((levelId - 1) % 3) + 1}` : null;
  if (!id || !maps[id]) {
    console.warn(`mapIdForLevel: no map for level ${levelId} (${level && level.mapType}); using single_1`);
    return 'single_1';
  }
  return id;
}
